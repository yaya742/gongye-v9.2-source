/* 用户协议与隐私政策
 *
 * 运营方信息来自运行时配置 window.__GONGYE_CONFIG__.legal（试用后端从 server/pilot.config.json 的 legal 读取）。
 * 没填的项会在页面上标成“待补充”。条款按当前代码的实际行为编写：改了数据处理方式，要同步改这里。
 * 正式上线前应由运营方核对，并请法务或学校相关部门审阅。
 */

import { href } from '../router.js';
import { esc } from '../lib/format.js';

function legalInfo(ctx) {
  const raw = (ctx.config && ctx.config.legal) || {};
  const value = (key, label) => (raw[key]
    ? esc(raw[key])
    : `<mark class="legal-pending">【${label}待补充】</mark>`);
  return {
    operator: value('operator', '运营方名称'),
    contact: value('contact', '联系邮箱'),
    effectiveDate: value('effectiveDate', '生效日期'),
    dataLocation: value('dataLocation', '服务器所在地'),
    complete: ['operator', 'contact', 'effectiveDate', 'dataLocation'].every((key) => !!raw[key])
  };
}

function page(ctx, { title, current, sections }) {
  const info = legalInfo(ctx);
  return `
  <div class="layout-1 legal-page">
    <nav class="legal-switch" aria-label="协议与政策">
      <a href="${href('/terms')}" ${current === 'terms' ? 'aria-current="page"' : ''}>用户协议</a>
      <a href="${href('/privacy')}" ${current === 'privacy' ? 'aria-current="page"' : ''}>隐私政策</a>
    </nav>
    <article class="card legal-body">
      <h1>${title}</h1>
      <p class="tiny muted">生效日期：${info.effectiveDate} · 运营方：${info.operator}</p>
      ${info.complete ? '' : `<div class="notice notice-warn mt-3"><span>本页的运营方信息还没有填写完整，正式上线前需要补充并请相关部门审阅。</span></div>`}
      ${sections(info).map(([heading, body]) => `<section>
        <h2>${heading}</h2>
        ${body}
      </section>`).join('')}
    </article>
  </div>`;
}

